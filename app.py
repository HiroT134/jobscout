"""Read-only demo UI: browse scored listings. Run with: streamlit run app.py

Reads the database named by JOBSCOUT_DB (default data/demo.db) and never writes to it.
"""

import html
import sys
from pathlib import Path

import altair as alt
import pandas as pd
import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ui import data  # noqa: E402

COLUMNS = ["company", "title", "location", "date", "score", "verdict", "url"]
SELECTED = "selected_job"     # session key: job id shown in the detail panel, or None
SELECTED_FROM = "selected_from"  # session key: the table key whose row click set SELECTED
TABLE_IDS = "table_job_ids"   # session key: job ids in the order the table was last drawn
TABLE_NONCE = "table_nonce"   # session key: bumped to give the table a fresh, unselected key
# background and text colour per verdict; dark text keeps them readable in either theme
VERDICT_STYLE = {
    "shortlist": "background-color: #d3f2dc; color: #14532d; font-weight: 600",
    "maybe": "background-color: #fdeccb; color: #7a4a00; font-weight: 600",
    "skip": "background-color: #e7e8ea; color: #3f4650",
}

st.set_page_config(page_title="Job Scout demo", layout="wide")
st.title("Job Scout")
st.info("Demo data: every company, job, link and score here is fictional, generated by "
        "scripts/make_demo_db.py. The page is read-only and makes no API calls.")


jobs_tab, eval_tab, sample_tab = st.tabs(["Jobs", "Evaluation", "Sample deepdive"])

# The Evaluation and Sample deepdive tabs read static files only. They are drawn before the
# jobs view so that st.stop() there (no demo database) does not blank them.
with eval_tab:
    ev = data.load_evaluation()
    st.markdown(f"#### {ev['headline']}")
    st.markdown("\n".join(f"- {s}" for s in ev["summary"]))
    st.caption("Figures are from results.csv, the scoring runs behind EVALUATION.md. "
               "The labels behind them are real; no live API call is made on this page.")

    st.markdown("#### Agreement with my labels")
    rows = pd.DataFrame(data.agreement_chart_rows(ev))
    order = list(rows["run"])
    x = alt.X("run:N", sort=order, title=None, axis=alt.Axis(labelAngle=0))
    bars = alt.Chart(rows).mark_bar(cornerRadiusTopLeft=4, cornerRadiusTopRight=4, size=36).encode(
        x=x,
        y=alt.Y("agreement:Q", title="Agreement (%)", scale=alt.Scale(domain=[0, 100])),
        color=alt.Color("set:N", title=None, legend=alt.Legend(orient="top"),
                        scale=alt.Scale(domain=["Tuning (126 jobs)", "Held-out (40 jobs, run once)"],
                                        range=["#2a78d6", "#eb6834"])),
        tooltip=[alt.Tooltip("run:N", title="Run"), alt.Tooltip("agreement:Q", title="Agreement %", format=".1f"),
                 alt.Tooltip("label:N", title="Agreed"), alt.Tooltip("baseline:Q", title="Baseline %", format=".1f")],
    )
    values = bars.mark_text(dy=-8).encode(text=alt.Text("agreement:Q", format=".1f"), color=alt.value("gray"))
    baseline = rows["baseline"].iloc[0]
    rule = alt.Chart(pd.DataFrame({"y": [baseline]})).mark_rule(strokeDash=[6, 4], color="gray").encode(y="y:Q")
    rule_label = alt.Chart(pd.DataFrame({"y": [baseline]})).mark_text(
        align="left", dy=-8, color="gray").encode(
        x=alt.value(4), y="y:Q", text=alt.value(f"Skip-everything baseline, {baseline:.1f}%"))
    st.altair_chart(bars + values + rule + rule_label, width="stretch")

    tune, held = ev["iterations"][-1], ev["holdout"]
    st.markdown(f"#### Tuning set: {tune['compared']} jobs, skip-everything baseline {data.pct(tune['baseline'])}")
    st.table(pd.DataFrame(data.tuning_table(ev)).set_index("Iteration"))
    st.markdown(f"#### Held-out set: {held['compared']} jobs, baseline {data.pct(held['baseline'])}, "
                "final rubric, run once")
    st.table(pd.DataFrame(data.holdout_table(ev)).set_index("Metric"))
    st.caption(f"Noise check: {ev['noise_check']}")

    st.markdown("#### What this does and does not show")
    st.markdown("\n".join(f"- {c}" for c in ev["caveats"]))

with sample_tab:
    st.warning("FICTIONAL SAMPLE. Nothing here is a real employer, person or application. "
               "The employer, the candidate and every source are made up, and the text was written "
               "by hand for this demo. No live API call is made: this tab only shows a static file.")
    st.markdown(data.sample_deepdive())

with jobs_tab:
    try:
        conn = data.connect()
    except FileNotFoundError as e:
        st.error(f"{e}. Build it with: python scripts/make_demo_db.py")
        st.stop()

    try:
        jobs = data.all_jobs(conn)
        locations = data.locations(conn)
        bounds = data.date_bounds(conn)
    finally:
        conn.close()

    search_col, verdict_col, location_col, score_col, date_col = st.columns([3, 3, 3, 2, 2], gap="medium")
    company = search_col.text_input("Search company", placeholder="e.g. Kauri")
    verdicts = verdict_col.multiselect("Verdict", data.VERDICTS, default=data.VERDICTS)
    chosen_locations = location_col.multiselect("Location", locations, placeholder="All locations")
    lo, hi = score_col.slider("Score", 0, 100, (0, 100))
    date_from = date_to = None
    if bounds:
        picked = date_col.date_input("First seen", value=bounds, min_value=bounds[0], max_value=bounds[1])
        # a range picker returns a single date while the second one is still being chosen
        picked = tuple(picked) if isinstance(picked, (list, tuple)) else (picked,)
        date_from = picked[0] if picked else None
        date_to = picked[1] if len(picked) > 1 else date_from

    shown = data.filter_jobs(jobs, data.Filters(lo, hi, verdicts, company, chosen_locations, date_from, date_to))
    st.subheader(f"{len(shown)} of {len(jobs)} jobs match the filters")

    # Selection is kept as a job id in session state, never as a row position. A row position
    # only means something for the rows the table was drawn with, so the table gets a fresh
    # key whenever those rows change: the selection stored under the current key then always
    # refers to `ids`, and a stale highlight can never point at a different job.
    ss = st.session_state
    ids = [j["job_id"] for j in shown]
    if ss.get(TABLE_IDS) != ids:
        ss[TABLE_IDS] = ids
        ss[TABLE_NONCE] = ss.get(TABLE_NONCE, 0) + 1
    table_key = f"jobs_table_{ss[TABLE_NONCE]}"
    table_state = ss.get(table_key)
    rows = list(table_state["selection"]["rows"]) if table_state else []
    if rows:
        ss[SELECTED], ss[SELECTED_FROM] = data.job_id_for_row(ids, rows), table_key
    elif ss.get(SELECTED_FROM) == table_key:
        ss[SELECTED] = None  # the viewer clicked the selected row again to deselect it
    # a job that was filtered out is dropped, so it does not come back when filters widen
    selected = ss[SELECTED] = data.visible_selection(ss.get(SELECTED), ids)


    def close_panel() -> None:
        ss[SELECTED] = None
        ss[TABLE_NONCE] = ss.get(TABLE_NONCE, 0) + 1  # new table key clears the row highlight


    table = pd.DataFrame([{k: j[k] for k in COLUMNS} for j in shown], columns=COLUMNS)
    table["date"] = pd.to_datetime(table["date"])
    styled = table.style.map(lambda v: VERDICT_STYLE.get(v, ""), subset=["verdict"])

    if selected:
        table_area, panel = st.columns([2, 1], gap="medium")
    else:
        st.caption("Click a row to see why it got its verdict.")
        table_area, panel = st.container(), None

    table_area.dataframe(
        styled,
        key=table_key,
        on_select="rerun",
        selection_mode="single-row",
        hide_index=True,
        width="stretch",
        column_order=COLUMNS,
        column_config={
            "company": st.column_config.TextColumn("Company"),
            "title": st.column_config.TextColumn("Title", width="large"),
            "location": st.column_config.TextColumn("Location"),
            "date": st.column_config.DateColumn("Date", format="YYYY-MM-DD"),
            "score": st.column_config.ProgressColumn("Score", min_value=0, max_value=100, format="%d"),
            "verdict": st.column_config.TextColumn("Verdict"),
            "url": st.column_config.LinkColumn("Link", display_text="View"),
        },
    )

    if selected:
        conn = data.connect()
        try:
            job = data.job_detail(conn, selected)
        finally:
            conn.close()
        with panel.container(border=True):
            if job is None:
                st.warning("This job is no longer in the database.")
            else:
                st.markdown(f"### {html.escape(job['title'])}")
                st.markdown(f"**{html.escape(job['company'])}**  \n{html.escape(job['location'])} · "
                            f"first seen {job['date']:%Y-%m-%d}")
                st.markdown(
                    f"<span style='{VERDICT_STYLE.get(job['verdict'], '')}; padding: 0.2rem 0.7rem; "
                    f"border-radius: 999px'>{html.escape(job['verdict'])}</span>", unsafe_allow_html=True)
                st.progress(job["score"] / 100, text=f"Score {job['score']} / 100")
                if job["reasons"]:
                    st.markdown("**Why this verdict**")
                    st.markdown("\n".join(f"- {html.escape(r)}" for r in job["reasons"]))
                st.link_button("View listing", job["url"])
            st.button("Close", on_click=close_panel)
